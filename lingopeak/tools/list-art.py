#!/usr/bin/env python3
"""Writes web/js/art-files.js: the list of drawn pictures in web/img, so the
app knows which ones exist (anything missing gets a placeholder)."""
import os

from PIL import Image

root = os.path.join(os.path.dirname(__file__), '..', 'web')
files = sorted(
    os.path.relpath(os.path.join(d, f), os.path.join(root, 'img')).replace(os.sep, '/')
    for d, _, fs in os.walk(os.path.join(root, 'img')) for f in fs if f.endswith(('.webp', '.png'))
)
with open(os.path.join(root, 'js', 'art-files.js'), 'w') as out:
    out.write('// Generated by tools/list-art.py — the pictures in img/ and their sizes.\n')
    out.write('const ART_SIZES = {\n')
    for f in files:
        w, h = Image.open(os.path.join(root, 'img', f)).size
        out.write(f"  '{f}': [{w}, {h}],\n")
    out.write('};\nconst ART_FILES = new Set(Object.keys(ART_SIZES));\n')
print(len(files), 'pictures')
